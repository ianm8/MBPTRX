  static void __not_in_flash_func(process_cw)(const bool keydown,int16_t &out_i,int16_t &out_q)
  {
    static const int32_t cw_gain = 100;
    static const int32_t set_gain = cw_gain * 1024 / 100;
    static const int32_t max_sig = 361;
    volatile static uint32_t gaussian_phase = 0;
    volatile static enum cw_state_t
    {
      CW_STATE_KEYUP,
      CW_STATE_KEYDOWN,
      CW_STATE_KEY_TRANSITION_TO_DOWN,
      CW_STATE_KEY_TRANSITION_TO_UP
    }
    cw_state = CW_STATE_KEYUP;
    switch (cw_state)
    {
      case CW_STATE_KEYUP:
      {
        out_i = 0;
        out_q = 0;
        // if keydown then transition to key down
        if (keydown)
        {
          gaussian_phase = GAUSSIAN_TAB - 1;
          cw_state = CW_STATE_KEY_TRANSITION_TO_DOWN;
        }
        break;
      }
      case CW_STATE_KEY_TRANSITION_TO_DOWN:
      {
        // stay here until gaussian done
        const int32_t gaussian = gaussian_tab[gaussian_phase];
        out_i = out_q = (((max_sig * gaussian) >> 15) * set_gain) >> 10;
        gaussian_phase--;
        if (gaussian_phase==0)
        {
          cw_state = CW_STATE_KEYDOWN;
        }
        break;
      }
      case CW_STATE_KEYDOWN:
      {
        // stay here while key down
        out_i = out_q = (max_sig * set_gain) >> 10;
        if (keydown)
        {
          return;
        }
        gaussian_phase = 0;
        cw_state = CW_STATE_KEY_TRANSITION_TO_UP;
        break;
      }
      case CW_STATE_KEY_TRANSITION_TO_UP:
      {
        // stay here until gaussian done
        const int32_t gaussian = gaussian_tab[gaussian_phase];
        out_i = out_q = (((max_sig * gaussian) >> 15) * set_gain) >> 10;
        gaussian_phase++;
        if (gaussian_phase>=GAUSSIAN_TAB)
        {
          cw_state = CW_STATE_KEYUP;
        }
        break;
      }
    }
  }

  static const int16_t __not_in_flash_func(sidetone)(const bool keydown)
  {
    static const uint64_t tone = 700ull;
    static const uint32_t level = 3u;
    static const uint32_t shift = 8u - level;
    static const uint32_t phase = (uint32_t)((tone * (1ull << 32)) / SAMPLERATE);
    volatile static uint32_t dds = 0;
    // position in gaussian_tab: 0 = full level, GAUSSIAN_TAB-1 = silent
    // walks one entry per sample so the tone has the same edge as the RF
    static uint32_t envelope_phase = GAUSSIAN_TAB - 1;
    if (keydown)
    {
      if (envelope_phase>0)
      {
        envelope_phase--;
      }
    }
    else
    {
      if (envelope_phase<GAUSSIAN_TAB-1)
      {
        envelope_phase++;
      }
    }
    int16_t s = 0;
    if (envelope_phase<GAUSSIAN_TAB-1)
    {
      // scale tone by envelope, single rounded shift
      const int32_t envelope = gaussian_tab[envelope_phase];
      const int32_t tone_sample = dds_sin_tab[dds>>22];
      s = (int16_t)((tone_sample * envelope + (1 << (14 + shift))) >> (15 + shift));
    }
    dds += phase;
    return s;
  }
